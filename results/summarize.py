#!/usr/bin/env python3
"""Generate docs/RESULTS.md from the raw result files, so no number is hand-copied."""
import json, os, platform
from pathlib import Path

R = Path(__file__).parent
rows = [json.loads(l) for l in (R / "bench.jsonl").read_text().splitlines() if l.strip()]
chaos = [json.loads(l) for l in (R / "chaos.jsonl").read_text().splitlines() if l.strip()]
sim = json.loads((R / "sim.json").read_text())
mut_sim = [json.loads(l) for l in (R / "mutations_sim.jsonl").read_text().splitlines() if l.strip()]
mut_chaos = [json.loads(l) for l in (R / "mutations_chaos.jsonl").read_text().splitlines() if l.strip()]

fsync = next(r["result"] for r in rows if r["probe"] == "fsync")
loads = [r["result"] for r in rows if r["probe"] == "load"]
closed = [r for r in loads if r["mode"] == "closed"]
opened = [r for r in loads if r["mode"] == "open"]
recov = [r["result"] for r in rows if r["probe"] == "recovery"]
ms = lambda us: f"{us / 1000:.1f} ms"

out = []
w = out.append
cpu = os.cpu_count()
kernel = platform.release()
w("# Results\n")
w("Generated by `results/summarize.py` from the raw files in `results/`.\n")
w("## Test environment and how to read these numbers\n")
is_mac = platform.system() == "Darwin"
w(f"- One Mac: {cpu} CPU cores, macOS, internal SSD." if is_mac else f"- One cloud VM: {cpu} vCPUs, Linux {kernel}, ext4 on a virtual disk.")
w("- **All nodes and all benchmark clients shared those CPUs** and talked over loopback.")
w("  There is no real network delay here. Across machines, latency will be higher.")
w(f"- Measured fsync: {fsync['p50_us']} µs median, {fsync['p99_us']} µs p99.")
if is_mac:
    w("  On macOS this is a full flush to the drive (F_FULLFSYNC), which is much slower than plain fsync.")
else:
    w("  That is fast for a real SSD and may mean the hypervisor acknowledges flushes early.")
    w("  On disks with slower fsync, expect higher latency.")
w("- Values were 128 bytes. Every write was fsynced before it was acknowledged.\n")

best3 = max((r for r in closed if r["nodes"] == 3), key=lambda r: r["ops_per_sec"])
best5 = max((r for r in closed if r["nodes"] == 5), key=lambda r: r["ops_per_sec"])
w("## Throughput and write latency\n")
w("Closed-loop: each client waits for a reply before sending again.\n")
w("| Nodes | Clients | Writes/sec | p50 | p99 | p99.9 | Errors | Leader elections |")
w("|---|---|---|---|---|---|---|---|")
for r in sorted(closed, key=lambda r: (r["nodes"], r["clients"])):
    w(f"| {r['nodes']} | {r['clients']} | {r['ops_per_sec']:,} | {ms(r['p50_us'])} | {ms(r['p99_us'])} | {ms(r['p999_us'])} | {r['errors']} | {r['leader_elections']} |")
w("")
w(f"Peak measured: **{best3['ops_per_sec']:,} writes/sec on 3 nodes** ({best3['clients']} clients, p99 {ms(best3['p99_us'])})")
w(f"and **{best5['ops_per_sec']:,} writes/sec on 5 nodes** ({best5['clients']} clients, p99 {ms(best5['p99_us'])}).\n")
if opened:
    w("Open-loop: a fixed arrival rate, with latency measured from each write's scheduled start,")
    w("so stalls cannot hide. This is the fairer latency figure.\n")
    w("| Nodes | Target rate | Achieved | p50 | p99 | p99.9 | Errors |")
    w("|---|---|---|---|---|---|---|")
    for r in sorted(opened, key=lambda r: r["target_rate"]):
        w(f"| {r['nodes']} | {r['target_rate']:,}/s | {r['ops_per_sec']:,}/s | {ms(r['p50_us'])} | {ms(r['p99_us'])} | {ms(r['p999_us'])} | {r['errors']} |")
    w("")

w("## Recovery after SIGKILL of the leader\n")
w("Under steady write load. `First write acked` is from the kill to the first acknowledged")
w("write that began after the old leader was dead.\n")
w("| Nodes | Election timeout | Trials done | New leader p50 | New leader p99 | First write acked p50 | First write acked p99 | Max |")
w("|---|---|---|---|---|---|---|---|")
for r in recov:
    t = f"{r['election_min_ticks'] * 10}–{r['election_max_ticks'] * 10} ms"
    n, a = r["new_leader"], r["first_write_acked"]
    w(f"| {r['nodes']} | {t} | {r['completed']}/{r['trials']} | {n['p50_ms']:.0f} ms | {n['p99_ms']:.0f} ms | {a['p50_ms']:.0f} ms | {a['p99_ms']:.0f} ms | {a['max_ms']:.0f} ms |")
w("")

passed = sum(c["passed"] for c in chaos)
faults = {}
for c in chaos:
    for k, v in c["faults"].items():
        faults[k] = faults.get(k, 0) + v
tot = lambda k: sum(c[k] for c in chaos)
w("## Chaos test on real processes\n")
sizes = sorted({c["nodes"] for c in chaos})
w(f"{len(chaos)} runs on {' and '.join(map(str, sizes))} nodes, {chaos[0]['seconds']} s of faults each, with real TCP, real files and SIGKILL.\n")
w("| Measure | Result |")
w("|---|---|")
w(f"| Runs passed | **{passed} / {len(chaos)}** |")
w(f"| Acknowledged writes verified | {tot('acked_writes'):,} |")
lost = sum(1 for c in chaos for v in c["violations"] if v.startswith("LOST_WRITE"))
dup = sum(1 for c in chaos for v in c["violations"] if v.startswith("DOUBLE_APPLY"))
w(f"| Acknowledged writes lost | **{lost}** |")
w(f"| Writes applied twice | **{dup}** |")
w(f"| Successful reads checked for linearizability | {tot('ok_reads'):,} |")
w(f"| Writes with unknown outcome (client gave up) | {tot('indeterminate_writes'):,}, of which {tot('indeterminate_applied'):,} took effect |")
w(f"| Faults injected | {sum(faults.values()):,} |")
w(f"| Leaders elected | {tot('leader_elections'):,} |")
w(f"| Node process starts | {tot('process_starts'):,} |")
w(f"| Snapshots taken / installed from a leader | {tot('snapshots_taken'):,} / {tot('snapshots_installed'):,} |")
w(f"| Torn log tails repaired at startup | {tot('torn_tails_repaired'):,} |")
w(f"| Client retries | {tot('client_retries'):,} |\n")
w("Faults by type:\n")
w("| Fault | Count |")
w("|---|---|")
for k, v in sorted(faults.items()):
    w(f"| `{k}` | {v} |")
w("")
for c in chaos:
    if not c["passed"]:
        w(f"**Failing run, seed {c['seed']}, {c['nodes']} nodes:** `{c['violations'][:3]}`\n")

w("## Deterministic simulation\n")
w(f"{sim['seeds']:,} random seeds, varying cluster size from 3 to 7 nodes, on a simulated network and disk.\n")
w("| Measure | Result |")
w("|---|---|")
w(f"| Seeds that found a violation | **{sim['failing_seeds']}** |")
w(f"| Acknowledged writes verified | {sim['acked_writes']:,} |")
w(f"| Reads verified | {sim['ok_reads']:,} |")
w(f"| Simulated crashes | {sim['crashes']:,} (including {sim['crashes_before_fsync']:,} before an fsync) |")
w(f"| Partitions | {sim['partitions']:,} |")
w(f"| Leaders elected | {sim['leaders_elected']:,} |")
w(f"| Snapshots installed | {sim['snapshots_installed']:,} |")
w(f"| Log truncations | {sim['truncations'] if 'truncations' in sim else sim['log_truncations']:,} |\n")

w("## Can the tests actually catch bugs?\n")
w("Each row rebuilds the system with one deliberate bug. 'Simulator' counts failing seeds out")
w("of 5,000. 'Real chaos' runs up to three 30-second runs and stops at the first detection.\n")
w("| Injected bug | Simulator | Caught as | Real chaos | Caught as |")
w("|---|---|---|---|---|")
for m in mut_sim:
    b = m["bug"]
    s = m["result"]
    runs = [x["result"] for x in mut_chaos if x["bug"] == b]
    hit = [x for x in runs if not x["passed"]]
    kinds = sorted({v.split(" ")[0] for x in hit for v in x["violations"]} - {"..."})
    skinds = ", ".join(k for k in sorted(s["violations_by_kind"]) if k != "...") or "—"
    chaos_cell = f"caught on run {runs.index(hit[0]) + 1}" if hit else f"not caught ({len(runs)} runs)"
    w(f"| `{b}` | {s['failing_seeds']:,} / {s['seeds']:,} | {skinds} | {chaos_cell} | {', '.join(kinds) or '—'} |")
w("")
w("`commit_old_term` (Figure 8 of the Raft paper) needs a very specific interleaving. It is")
w("caught by the directed test `figure8_mutation_is_detected`, not by random search.\n")
caught = sum(1 for m in mut_sim if any(not x["result"]["passed"] for x in mut_chaos if x["bug"] == m["bug"]))
w(f"Real-process chaos caught {caught} of the {len(mut_sim)} bugs in these short runs, and missed some that can lose")
w("writes (`vote_ignores_log`, `skip_fsync`). Those need rare timing or a real power cut, so a clean chaos")
w("pass is not proof on its own. The simulator and directed tests cover what chaos misses.\n")
w("`skip_fsync` shows why both layers exist: SIGKILL does not lose data held in the kernel page")
w("cache, so real-process chaos cannot see a missing fsync. The simulated disk can.\n")
w("## Limits of this evidence\n")
w("- No client reached its 6-second deadline in the chaos runs, so `Indeterminate` outcomes were exercised only in the simulator.")
w("- SIGKILL produced no torn log tails, because each write reached the kernel whole. Torn-write recovery is covered by")
w("  `torn_write_at_every_byte_recovers_a_clean_prefix` and the simulator, not by the chaos runs.")
w("- Real power loss was not tested. Everything ran on one host, so real network behaviour was only approximated by the proxy.")
w("- An earlier chaos batch was thrown away after a harness bug stopped one node from ever starting (see `chaos_before_port_fix.jsonl`).")
w("  The 24 runs above came after that fix.")
w("- After this campaign one more harness fix landed: a race in the test proxy crashed the harness once during a mutation run,")
w("  and that run was repeated. Only test code changed; the server code is the code measured here.\n")
(R.parent / "docs" / "RESULTS.md").write_text("\n".join(out))
print("\n".join(out))
